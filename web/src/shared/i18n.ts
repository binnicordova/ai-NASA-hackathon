const DICTIONARIES: Record<Lang, Record<Key, string>> = { es, en };
const MONTH_NAMES: Record<Lang, string[]> = {
  es: ['ene', 'feb', 'mar', 'abr', 'may', 'jun', 'jul', 'ago', 'sep', 'oct', 'nov', 'dic'],
  en: ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'],
};
const STORAGE_KEY = 'fire-calendar-lang';

function initialLang(): Lang {
  const fromUrl = new URLSearchParams(location.search).get('lang');
  if (fromUrl === 'es' || fromUrl === 'en') return fromUrl;
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored === 'es' || stored === 'en') return stored;
  } catch {
    /* almacenamiento bloqueado: se usa el idioma por defecto */
  }
  return navigator.language.toLowerCase().startsWith('en') ? 'en' : 'es';
}

let current: Lang = initialLang();

export const lang = (): Lang => current;
export const locale = (): string => (current === 'es' ? 'es-PE' : 'en-US');
export const monthNames = (): string[] => MONTH_NAMES[current];

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return DICTIONARIES[current][key].replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ''));
}

export function setLang(next: Lang): void {
  current = next;
  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch {
    /* sin almacenamiento: el idioma vale solo para esta visita */
  }
}

/** Traduce el HTML estático: data-i18n (texto), data-i18n-title, data-i18n-aria y data-i18n-placeholder. */
export function translateDocument(root: ParentNode = document): void {
  document.documentElement.lang = current;
  document.title = t('app.title');
  root.querySelectorAll<HTMLElement>('[data-i18n]').forEach((node) => (node.textContent = t(node.dataset.i18n as Key)));
  root.querySelectorAll<HTMLElement>('[data-i18n-title]').forEach((node) => (node.title = t(node.dataset.i18nTitle as Key)));
  root.querySelectorAll<HTMLElement>('[data-i18n-aria]').forEach((node) => node.setAttribute('aria-label', t(node.dataset.i18nAria as Key)));
}
